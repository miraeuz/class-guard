    public static void SetLanguage(string lang)
    {
        lang = (lang ?? "uz").Trim().ToLowerInvariant();
        if (lang is not ("uz" or "ru" or "en")) lang = "uz";
        if (Current == lang) return;
        Current = lang;
        try{Directory.CreateDirectory(Path.GetDirectoryName(LanguageFile)!);File.WriteAllText(LanguageFile,lang);}catch(IOException){}
        LanguageChanged?.Invoke();
    }

    public static string T(string key)
    {
        if (_tables.TryGetValue(Current, out var table) && table.TryGetValue(key, out var v))
            return v;
        if (_tables["uz"].TryGetValue(key, out var uz))
            return uz;
        return key;
    }
